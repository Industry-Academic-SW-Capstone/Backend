-- 미션 보상 지급 기록 (증권사)
--   대상: 미션 보상이 계좌 현금을 바꿀 때 정산 원장처럼 기록을 남겨, 현금을 기록만으로 다시 맞춰 볼 수 있게 하기 위함
--
-- 이 파일 전에 준 보상은 기록이 없다. 증권사가 부가의 보상 지급 요청(extra.events)을 받을 때부터 남는다.
-- Flyway 자동 실행이 꺼져 있어 이 파일은 자동 적용되지 않는다(V10~V20 과 같다).

CREATE TABLE IF NOT EXISTS broker.reward_payment (
    reward_payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          VARCHAR(64)    NOT NULL UNIQUE,
    account_id        BIGINT         NOT NULL,
    member_id         BIGINT         NOT NULL,
    amount            NUMERIC(19, 2) NOT NULL,
    created_at        TIMESTAMP(6)   NOT NULL,
    updated_at        TIMESTAMP(6),
    deleted_at        TIMESTAMP(6)
);

CREATE INDEX IF NOT EXISTS idx_reward_payment_account ON broker.reward_payment (account_id);
