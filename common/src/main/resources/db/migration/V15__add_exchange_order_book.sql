-- 거래소 오더북과 체결 원장
--   대상: 거래소가 증권사의 trade_order 를 같이 쓰지 않고 자기 테이블로 체결하기 위함
--
-- exchange_order: 오더북. 주문 번호는 증권사가 붙인 것을 그대로 쓴다. 시간 우선은 거래소에 도착한 시각(accepted_at)이다.
-- exchange_fill : 체결 원장. 여기서 붙은 번호가 통보로 건너가 증권사 execution 의 번호가 된다.
-- Flyway 자동 실행이 꺼져 있어 이 파일은 자동 적용되지 않는다(V10~V14 와 같다). 배포 전에 손으로 적용한다.

CREATE TABLE IF NOT EXISTS exchange_order (
    order_id        BIGINT         PRIMARY KEY,
    account_id      BIGINT         NOT NULL,
    stock_code      VARCHAR(20)    NOT NULL,
    order_method    VARCHAR(20)    NOT NULL,
    order_type      VARCHAR(20)    NOT NULL,
    price           NUMERIC(19, 2) NOT NULL,
    quantity        INTEGER        NOT NULL,
    filled_quantity INTEGER        NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    accepted_at     TIMESTAMP      NOT NULL
);

-- 체결 후보 조회(종목·방향·가격·도착 순서). 오더북에 남은 주문만 담는다.
CREATE INDEX IF NOT EXISTS idx_exchange_order_book
    ON exchange_order (stock_code, order_method, price, accepted_at)
    WHERE status = 'OPEN';

CREATE TABLE IF NOT EXISTS exchange_fill (
    fill_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    stock_code VARCHAR(20)    NOT NULL,
    price      NUMERIC(19, 2) NOT NULL,
    quantity   INTEGER        NOT NULL,
    filled_at  TIMESTAMP      NOT NULL
);

-- 이미 있는 미체결 주문을 오더북으로 옮긴다. 도착 시각은 원래 접수 시각을 쓴다.
INSERT INTO exchange_order (order_id, account_id, stock_code, order_method, order_type, price,
                            quantity, filled_quantity, status, accepted_at)
SELECT order_id, account_id, stock_code, order_method, order_type, price,
       quantity, filled_quantity, 'OPEN', created_at
FROM trade_order
WHERE status IN ('PENDING', 'PARTIALLY_FILLED') AND quantity > filled_quantity
ON CONFLICT (order_id) DO NOTHING;

-- 체결 번호가 기존 execution 번호와 겹치지 않게 그 뒤에서 시작한다.
DO $$
DECLARE next_id BIGINT;
BEGIN
    SELECT COALESCE(MAX(execution_id), 0) + 1 INTO next_id FROM execution;
    EXECUTE format('ALTER TABLE exchange_fill ALTER COLUMN fill_id RESTART WITH %s', next_id);
END $$;
