-- 거래소 샤드 DB 의 스키마. 샤드 설정이 있으면 기동 때 샤드마다 돌린다(ShardDataSourceConfig). 여러 번 돌려도 같다.
-- 운영 DB 의 V12·V13·V15·V18·V20·V22 를 다 적용한 거래소 schema 와 같은 모양이다. 엔티티나 그 V 파일이 바뀌면 같이 고친다.

CREATE SCHEMA IF NOT EXISTS exchange;

CREATE TABLE IF NOT EXISTS exchange.exchange_order (
    order_id        BIGINT         PRIMARY KEY,
    account_id      BIGINT         NOT NULL,
    stock_code      VARCHAR(20)    NOT NULL,
    order_method    VARCHAR(20)    NOT NULL,
    order_type      VARCHAR(20)    NOT NULL,
    price           NUMERIC(19, 2) NOT NULL,
    quantity        INTEGER        NOT NULL,
    filled_quantity INTEGER        NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    accepted_at     TIMESTAMP      NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_exchange_order_book
    ON exchange.exchange_order (stock_code, order_method, price, accepted_at)
    WHERE status = 'OPEN';

-- 체결 번호는 거래소 워커가 붙인다(FillIdGenerator). IDENTITY 를 두지 않는다.
CREATE TABLE IF NOT EXISTS exchange.exchange_fill (
    fill_id    BIGINT         PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    stock_code VARCHAR(20)    NOT NULL,
    price      NUMERIC(19, 2) NOT NULL,
    quantity   INTEGER        NOT NULL,
    filled_at  TIMESTAMP      NOT NULL
);

CREATE TABLE IF NOT EXISTS exchange.consumer_watermark (
    topic        VARCHAR(200) NOT NULL,
    partition_no INTEGER      NOT NULL,
    last_offset  BIGINT       NOT NULL,
    last_fill_id BIGINT,
    updated_at   TIMESTAMP    NOT NULL,
    PRIMARY KEY (topic, partition_no)
);

CREATE TABLE IF NOT EXISTS exchange.outbox_message (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic       VARCHAR(200) NOT NULL,
    message_key VARCHAR(200) NOT NULL,
    payload     TEXT         NOT NULL,
    created_at  TIMESTAMP    NOT NULL
);

-- 엔티티가 공통 모듈에 있어 거래소는 쓰지 않아도 둔다(validate 용, V20 과 같다).
CREATE TABLE IF NOT EXISTS exchange.processed_event (
    consumer     VARCHAR(50) NOT NULL,
    event_id     VARCHAR(64) NOT NULL,
    processed_at TIMESTAMP   NOT NULL,
    PRIMARY KEY (consumer, event_id)
);
